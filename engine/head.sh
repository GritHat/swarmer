#!/usr/bin/env bash
#: SWARMER, A UNIVERSAL AGENT SWARM FOR CODING AGENTS, version 5.3
#: (Claude Code, Codex, Antigravity, Gemini CLI, and every tool that reads AGENTS.md and Agent Skills)
#:
#: One file: the swarm's documents, its database of professionals and its engine, plus the commands to install
#: and convene it.
#:
#: Needs: bash, python3 >= 3.8 (standard library only), and a coding agent (`claude`, `codex`, `agy`, `gemini`, ...).
#:
#:   bash swarmer.sh install [--language en|it] [--targets claude,codex,...|auto] [--instructions] [--folder DIR]
#:   bash swarmer/swarmer.sh <single|fan-out|classic|jury|light-jury|full|plenary|expert|auto> "request"
#:   bash swarmer/swarmer.sh help            # every command, in the chosen language
#:   bash swarmer/swarmer.sh extensions --add crossroads   # the decision graph and the way back (an extension)
#:
#: Commands and options have aliases in every available language (see help).

set -euo pipefail

THIS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)/$(basename "${BASH_SOURCE[0]}")"

# @aliases-begin
# Generated by «build» from i18n/*.json and engine/compat.py: do not edit by hand.
canonical_command() {
    case "$1" in
        'install'|'installa') printf '%s' 'install' ;;
        'update'|'aggiorna') printf '%s' 'update' ;;
        'help'|'-h'|'--help'|'aiuto') printf '%s' 'help' ;;
        'tests'|'prove') printf '%s' 'tests' ;;
        *) printf '%s' "$1" ;;
    esac
}
canonical_option() {
    case "$1" in
        '--folder'|'--cartella') printf '%s' '--folder' ;;
        '--language'|'--lingua') printf '%s' '--language' ;;
        '--local'|'--locale') printf '%s' '--local' ;;
        '--instructions'|'--istruzioni') printf '%s' '--instructions' ;;
        '--force'|'--forza') printf '%s' '--force' ;;
        '--project-managed'|'--gestiti-dal-progetto') printf '%s' '--project-managed' ;;
        '--targets'|'--destinazioni') printf '%s' '--targets' ;;
        *) printf '%s' "$1" ;;
    esac
}
msg_en() {
    case "$1" in
        cli_prefix) printf '%s' 'swarmer: ' ;;
        sh_bad_folder) printf '%s' 'folder not allowed in {path}: {folder}' ;;
        sh_incomplete) printf '%s' 'this file is incomplete: download it again' ;;
        sh_missing_python) printf '%s' 'python3 is missing or too old (3.8 or newer is needed)' ;;
        sh_needs_folder) printf '%s' '-C wants a folder' ;;
        sh_needs_value) printf '%s' '{option}: a value is needed' ;;
        sh_not_a_project) printf '%s' '{root} does not look like a project: -C FOLDER install' ;;
        sh_not_installed) printf '%s' 'the swarm is not installed in {root} yet: bash swarmer.sh install' ;;
        sh_unknown_option) printf '%s' '{command}: unknown option: {option}' ;;
        sh_unsafe_name) printf '%s' 'this file contains an unsafe file name ({path}): not installing it' ;;
        *) printf '%s' "$1" ;;
    esac
}
msg_it() {
    case "$1" in
        cli_prefix) printf '%s' 'sciame: ' ;;
        sh_bad_folder) printf '%s' 'cartella non ammessa in {path}: {folder}' ;;
        sh_incomplete) printf '%s' 'questo file è incompleto: scaricalo di nuovo' ;;
        sh_missing_python) printf '%s' 'manca python3, o è troppo vecchio (serve il 3.8 o più recente)' ;;
        sh_needs_folder) printf '%s' '-C vuole una cartella' ;;
        sh_needs_value) printf '%s' '{option}: serve un valore' ;;
        sh_not_a_project) printf '%s' '{root} non sembra un progetto: -C CARTELLA installa' ;;
        sh_not_installed) printf '%s' 'in {root} lo sciame non c'\''è ancora: bash sciame.sh installa' ;;
        sh_unknown_option) printf '%s' '{command}: opzione sconosciuta: {option}' ;;
        sh_unsafe_name) printf '%s' 'questo file contiene un nome di file non ammesso ({path}): non lo installo' ;;
        *) printf '%s' "$1" ;;
    esac
}
default_folder() {
    case "$1" in
        it) printf '%s' 'sciame' ;;
        *) printf '%s' 'swarmer' ;;
    esac
}
LANGUAGES=('en' 'it')
SWARM_FOLDERS=('swarmer' 'sciame')
STATE_DIRS=('.swarmer' '.sciame')
FOLDER_KEYS=('folder' 'cartella')
ROOT_FILES=('ROOT' 'RADICE')
FACTORY_FILES=('FACTORY.json' 'FABBRICA.json')
LANGUAGE_FILES=('LANGUAGE' 'LINGUA')
ENGINES=('engine/swarmer.py' 'motore/sciame.py')
LANGUAGE_ENVS=('SWARMER_LANGUAGE' 'SCIAME_LINGUA')
# @aliases-end

SH_LANG="en"

# A message of bash in the language: msg KEY [NAME VALUE]…
msg() {
    local k="$1" m; shift
    if declare -F "msg_$SH_LANG" >/dev/null; then m="$("msg_$SH_LANG" "$k")"; else m="$(msg_en "$k")"; fi
    while [ $# -ge 2 ]; do m="${m//\{$1\}/$2}"; shift 2; done
    printf '%s' "$m"
}

fail() { printf '%s%s\n' "$(msg cli_prefix)" "$*" >&2; exit 1; }

need_python() {
    command -v python3 >/dev/null 2>&1 || fail "$(msg sh_missing_python)"
    python3 -I -B -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)' || fail "$(msg sh_missing_python)"
}

# The files at the end of this file, into a folder.
extract() {
    # A file name is relative, without «..», without empty components: otherwise the extraction stops (code 2).
    awk -v dest="$1" '
        /^#==== swarmer\.sh: file [A-Za-z0-9_.\/-]+ ====$/ {
            if (out) close(out)
            name = $4
            if (name ~ /^\// || name ~ /(^|\/)\.\.(\/|$)/ || name ~ /\/\// || (name in seen)) { bad = name; exit 2 }
            seen[name] = 1
            out = dest "/" name
            d = out; sub(/\/[^\/]*$/, "", d); system("mkdir -p \"" d "\"")
            printf "" > out; next }
        /^#==== swarmer\.sh: end of files ====$/ { if (out) close(out); out = ""; next }
        out { print > out }
        END { if (bad != "") exit 2 }
    ' "$THIS" || fail "$(msg sh_unsafe_name)"
    [ -f "$1/engine/swarmer.py" ] && [ -f "$1/db/professionals.json" ] || fail "$(msg sh_incomplete)"
}

# The first of a list of names that exists in a folder: first_in DIR NAME…
first_in() {
    local d="$1" n; shift
    for n in "$@"; do [ -e "$d/$n" ] && { printf '%s' "$n"; return 0; }; done
    return 1
}

# An installed copy has ROOT, FACTORY.json and the engine, under the new or the old names (an interrupted
# migration has some of each).
is_install() {
    first_in "$1" "${ROOT_FILES[@]}" >/dev/null && first_in "$1" "${FACTORY_FILES[@]}" >/dev/null \
        && first_in "$1" "${ENGINES[@]}" >/dev/null
}

# The swarm folder from the configuration of the project, validated: relative, without «..», not «.»; otherwise the
# installed one (swarmer/, then the others), otherwise the default of the language.
folder_from_config() {
    local r="$1" want="${2:-}" found=() d f x
    for d in "${STATE_DIRS[@]}"; do [ -e "$r/$d" ] && found+=("$d"); done
    [ "${#found[@]}" -le 1 ] || fail "both $r/${found[0]} and $r/${found[1]} exist"
    if [ "${#found[@]}" -eq 1 ]; then
        f="$r/${found[0]}/config.json"
        if [ -f "$f" ] && [ ! -L "$f" ]; then
            x="$(python3 -I -B -c '
import json, os, sys
c = json.load(open(sys.argv[1], encoding="utf-8"))
keys = [k for k in sys.argv[2:] if isinstance(c, dict) and k in c]
if len(keys) > 1:
    sys.exit("both %r and %r in %s" % (keys[0], keys[1], sys.argv[1]))
if keys:
    v = c[keys[0]]
    parts = str(v).split("/")
    if not isinstance(v, str) or not v or os.path.isabs(v) or ".." in parts or v in (".", "./") or "" in parts:
        sys.exit("folder not allowed in %s: %r" % (sys.argv[1], v))
    print(v, end="")' "$f" "${FOLDER_KEYS[@]}")" || exit 1
            [ -n "$x" ] && { printf '%s' "$x"; return; }
        fi
    fi
    for x in "${SWARM_FOLDERS[@]}"; do
        first_in "$r/$x" "${FACTORY_FILES[@]}" >/dev/null && { printf '%s' "$x"; return; }
    done
    default_folder "${want:-$(env_language)}"
}

env_language() {
    local v
    for v in "${LANGUAGE_ENVS[@]}"; do [ -n "${!v:-}" ] && { printf '%s' "${!v}"; return; }; done
    printf 'en'
}

# The language of the messages: LANGUAGE, then the 4.0 file, then the environment, then en.
set_language() {
    local d="$ROOT_DIR/$SWARM_DIR" n l=""
    for n in "${LANGUAGE_FILES[@]}"; do
        if [ -f "$d/$n" ] && [ ! -L "$d/$n" ]; then l="$(head -c 8 "$d/$n" | tr -d '\n')"; break; fi
    done
    [ -n "$l" ] || l="$(env_language)"
    case "$l" in [a-z][a-z]) SH_LANG="$l" ;; *) SH_LANG="en" ;; esac
}

# The swarm folder: the one of this file if it is an installed copy, otherwise the one of the configuration of the
# project, otherwise the installed one, otherwise <project>/swarmer (the default of the language).
find_install() {
    local here want="${1:-}"; here="$(dirname "$THIS")"
    if [ -n "${ROOT_DIR:-}" ]; then
        ROOT_DIR="$(cd "$ROOT_DIR" && pwd -P)"
        SWARM_DIR="$(folder_from_config "$ROOT_DIR" "$want")" || exit 1
    elif is_install "$here"; then
        ROOT_DIR="$(cd "$here/$(cat "$here/$(first_in "$here" "${ROOT_FILES[@]}")")" && pwd -P)"
        SWARM_DIR="$(python3 -I -B -c 'import os,sys; print(os.path.relpath(sys.argv[1], sys.argv[2]))' "$here" "$ROOT_DIR")"
    else
        ROOT_DIR="$PWD"
        SWARM_DIR="$(folder_from_config "$ROOT_DIR" "$want")" || exit 1
    fi
}

install() {
    local command="$1" typed="$2"; shift 2
    need_python
    if [ "$ROOT_DIR" = "/" ] || [ "$ROOT_DIR" = "$(cd "${HOME:-/}" && pwd -P)" ]; then
        fail "$(msg sh_bad_folder root "$ROOT_DIR")"
    fi
    local args=()
    while [ $# -gt 0 ]; do
        case "$(canonical_option "$1")" in
            --folder) [ $# -ge 2 ] || fail "$(msg sh_needs_value option "$1")"; SWARM_DIR="${2%/}"; shift 2 ;;
            --language) [ $# -ge 2 ] || fail "$(msg sh_needs_value option "$1")"; args+=(--language "$2"); shift 2 ;;
            --local) [ $# -ge 2 ] || fail "$(msg sh_needs_value option "$1")"; args+=(--local "$2"); shift 2 ;;
            --instructions) args+=(--instructions); shift ;;
            --force) args+=(--force); shift ;;
            --project-managed) args+=(--project-managed); shift ;;
            --targets) [ $# -ge 2 ] || fail "$(msg sh_needs_value option "$1")"; args+=(--targets "$2"); shift 2 ;;
            *) fail "$(msg sh_unknown_option command "$typed" option "$1")" ;;
        esac
    done
    SWARMER_TMP="$(mktemp -d)"
    trap 'rm -rf "${SWARMER_TMP:-}"' EXIT
    extract "$SWARMER_TMP"
    cp "$THIS" "$SWARMER_TMP/swarmer.sh"
    python3 -I -B "$SWARMER_TMP/engine/swarmer.py" "$command" --from "$SWARMER_TMP" --root "$ROOT_DIR" \
        --folder "$SWARM_DIR" ${args[@]+"${args[@]}"}
}

main() {
    ROOT_DIR=""
    SWARM_DIR=""   # never from the environment: the folder comes from --folder, the installed copy or the config
    if [ "${1:-}" = "-C" ]; then
        if [ $# -lt 2 ]; then
            # no project yet: the language of the installed copy this file belongs to, if it is one
            ROOT_DIR="$(dirname "$THIS")"; SWARM_DIR="."; set_language
            fail "$(msg sh_needs_folder)"
        fi
        ROOT_DIR="$2"; shift 2
    fi
    local typed="${1:-help}" command; command="$(canonical_command "$typed")"
    [ $# -eq 0 ] || shift
    local want="" prev="" a
    for a in "$@"; do
        [ "$prev" = "--language" ] && want="$a"
        prev="$(canonical_option "$a")"
    done
    SH_LANG="$(env_language)"
    find_install "$want"
    set_language
    case "$command" in
        help)
            sed -n 's/^#: \{0,1\}//p' "$THIS"
            if first_in "$ROOT_DIR/$SWARM_DIR" "${ENGINES[@]}" >/dev/null; then
                local l="$SH_LANG"
                [ -f "$ROOT_DIR/$SWARM_DIR/docs/$l/_HELP.txt" ] || l="en"
                [ -f "$ROOT_DIR/$SWARM_DIR/docs/$l/_HELP.txt" ] && cat "$ROOT_DIR/$SWARM_DIR/docs/$l/_HELP.txt"
                # the help lines of the enabled extensions (their i18n key «help»)
                if command -v python3 >/dev/null 2>&1 && [ -f "$ROOT_DIR/$SWARM_DIR/engine/swarmer.py" ]; then
                    python3 -I -B -c 'import sys, pathlib; s = pathlib.Path(sys.argv[1]).resolve(); sys.path.insert(0, str(s / "engine")); import swarmer; print(swarmer.extensions_help(s, sys.argv[2]), end="")' \
                        "$ROOT_DIR/$SWARM_DIR" "$l" 2>/dev/null || true
                fi
            fi
            return 0 ;;
        install|update)
            # update: with the files of this swarmer.sh, without touching those changed in the project (they go
            # next to them, .new); a 4.0 installation is migrated.
            install "$command" "$typed" "$@" ;;
        tests)
            need_python
            [ -f "$ROOT_DIR/$SWARM_DIR/engine/swarmer.py" ] || fail "$(msg sh_not_installed root "$ROOT_DIR")"
            local rc=0 p
            for p in "$ROOT_DIR/$SWARM_DIR"/tests/test_*.py; do python3 -I -B "$p" || rc=1; done
            exit "$rc" ;;
        *)
            need_python
            [ -f "$ROOT_DIR/$SWARM_DIR/engine/swarmer.py" ] || fail "$(msg sh_not_installed root "$ROOT_DIR")"
            exec python3 -I -B "$ROOT_DIR/$SWARM_DIR/engine/swarmer.py" --swarm "$ROOT_DIR/$SWARM_DIR" "$command" "$@" ;;
    esac
}

main "$@"
